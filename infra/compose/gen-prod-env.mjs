#!/usr/bin/env node
// Generates an env file for the production compose stack (compose.yml + compose.prod.yml) with a fresh random
// secret for every password — used by the local prod-stack run (infra/README.md), the CI `deploy-ready` config check
// and infra/compose/smoke.sh. No env file with dummy secrets is ever committed.
//   node infra/compose/gen-prod-env.mjs --out .env.prod.local [--domain applyra.localhost]
// Refuses to overwrite an existing file; writes it with mode 0600. Secrets are hex (URL-safe: compose builds the
// connection URLs from them). The real host's env is rendered by deploy-prod.yml from Environment secrets.
import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';

const { values } = parseArgs({
  options: {
    out: { type: 'string' },
    domain: { type: 'string', default: 'applyra.localhost' },
  },
  strict: true,
});
if (!values.out) {
  console.error('usage: gen-prod-env.mjs --out <file> [--domain <root domain>]');
  process.exit(1);
}
const domain = values.domain;
if (!/^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/.test(domain)) {
  console.error(`gen-prod-env: invalid domain "${domain}"`);
  process.exit(1);
}

const secret = (bytes = 32) => randomBytes(bytes).toString('hex');

const lines = [
  '# Generated by infra/compose/gen-prod-env.mjs — local/CI prod-stack values. Never commit, never reuse.',
  `ROOT_DOMAIN=${domain}`,
  `APP_DOMAIN=app.${domain}`,
  `API_DOMAIN=api.${domain}`,
  `POSTGRES_PASSWORD=${secret()}`,
  `APPLYRA_APP_PASSWORD=${secret()}`,
  `APPLYRA_MAINTENANCE_PASSWORD=${secret()}`,
  `APPLYRA_BACKUP_PASSWORD=${secret()}`,
  `APPLYRA_METRICS_PASSWORD=${secret()}`,
  `REDIS_PASSWORD=${secret()}`,
  `BETTER_AUTH_SECRET=${secret(48)}`,
  '# Only satisfy compose.yml interpolation (compose interpolates every file before profiles apply); the dev-only',
  '# minio services never start in prod.',
  'MINIO_ROOT_USER=unused-dev-only',
  `MINIO_ROOT_PASSWORD=${secret()}`,
  '# Comma-separated emails allowed to sign up; empty = sign-up closed.',
  'AUTH_SIGNUP_ALLOWLIST=',
  '# Optional (both or neither): Google OAuth client for this domain.',
  'GOOGLE_CLIENT_ID=',
  'GOOGLE_CLIENT_SECRET=',
  '',
];

try {
  // flag 'wx': fail if the file exists (no silent overwrite of someone's secrets).
  writeFileSync(values.out, lines.join('\n'), { flag: 'wx', mode: 0o600 });
} catch (error) {
  const code = /** @type {NodeJS.ErrnoException} */ (error).code;
  console.error(
    code === 'EEXIST'
      ? `gen-prod-env: ${values.out} already exists — delete it first`
      : `gen-prod-env: ${String(error)}`,
  );
  process.exit(1);
}
console.log(`gen-prod-env: wrote ${values.out} (mode 0600)`);
